def test_compress_makes_a_small_mono_16k_upload(stereo_wav):
    from lyricfield import transcribe as T
    out = T._compress(stereo_wav)
    info = R._ffprobe(out)
    assert info is not None
    audio = next(s for s in info["streams"] if s.get("codec_type") == "audio")
    assert int(audio.get("channels", 1)) == 1
    assert out.stat().st_size < stereo_wav.stat().st_size


def test_compress_trims_from_the_start(stereo_wav):
    """Seeking is what trims, not a filter: `adelay` with one value moves only
    the first channel, and the downmix then restores the original timing."""
    from lyricfield import transcribe as T
    whole = R._ffprobe(T._compress(stereo_wav, 0.0))
    trimmed = R._ffprobe(T._compress(stereo_wav, 3.0))
    a = float(whole["format"]["duration"])
    b = float(trimmed["format"]["duration"])
    assert a - b == pytest.approx(3.0, abs=0.4)
