"""The bridge between the repo and the running TouchDesigner project.

Source of truth is the repo. TD holds a thin shell -- a Script TOP, two character
DATs, a cue table DAT, a params DAT, and the render chain -- and everything that
defines behaviour is pushed in from here. Edit `td/field_callbacks.py` in VSCode,
run `push`, see it in TD.

`pull_cues` goes the other way, and exists for recovery: cue tables built by hand
inside a .toe before this package existed can be lifted straight out into a TSV.
"""

from __future__ import annotations

from pathlib import Path

from .config import Config
from .cues import CueTable
from .td_client import TDClient, TDError

HERE = Path(__file__).parent
FIELD_SCRIPT = HERE / "td" / "field_callbacks.py"

# Operator names inside the TD project. These match the network as it was built
# live, rather than renaming operators TD is actively cooking.
ROOT = "/project1"
SCRIPT_TOP = f"{ROOT}/v7_script"
CALLBACKS = f"{ROOT}/v7_script_callbacks"
PARAMS_DAT = f"{ROOT}/params"          # created on first push
CUE_DAT = f"{ROOT}/lyrics"
DIM_DAT = f"{ROOT}/v7_chars_dim"
LIT_DAT = f"{ROOT}/v7_chars_lit"
OUT_TOP = f"{ROOT}/out"


def _py_repr(v) -> str:
    if isinstance(v, str):
        return repr(v)
    if isinstance(v, bool):
        return "True" if v else "False"
    if isinstance(v, (int, float)):
        return repr(v)
    if isinstance(v, (list, tuple)):
        return "[" + ", ".join(_py_repr(x) for x in v) + "]"
    if isinstance(v, dict):
        return "{" + ", ".join(f"{_py_repr(k)}: {_py_repr(x)}" for k, x in v.items()) + "}"
    raise TypeError(f"cannot emit {type(v)}")


def push_params(client: TDClient, cfg: Config) -> None:
    """Write the config as a Python dict into the params DAT."""
    p = cfg.as_params()
    body = [
        "# Generated by lyricfield.sync -- do not edit in TouchDesigner.",
        "# Change values in data/config.toml and push again.",
        "",
        "P = {",
    ]
    for k, v in sorted(p.items()):
        body.append(f"    {_py_repr(k)}: {_py_repr(v)},")
    body.append("}")
    client.write(PARAMS_DAT, "\n".join(body))


def push_field(client: TDClient) -> None:
    """Push the field script into the Script TOP's callbacks DAT."""
    client.write(CALLBACKS, FIELD_SCRIPT.read_text(encoding="utf-8"))


def push_cues(client: TDClient, table: CueTable) -> None:
    client.write(CUE_DAT, table.to_dat_text())


def pull_cues(client: TDClient, dat: str = CUE_DAT) -> CueTable:
    """Recover a cue table that only exists inside a .toe.

    Uses `dat_text`, not `read` -- the read tool formats for display and prefixes
    each line with its number, which silently shifts every column when parsed.
    """
    return CueTable.from_dat_text(client.dat_text(dat))


def reset_field_state(client: TDClient) -> None:
    """Clear the field script's cached layout so the next cook rebuilds."""
    client.run(
        "def main():\n"
        f"    d = op({CALLBACKS!r})\n"
        "    if d is None:\n"
        "        return 'no callbacks DAT'\n"
        "    m = d.module\n"
        "    if hasattr(m, 'S'):\n"
        "        m.S.clear()\n"
        "    return 'cleared'\n"
        "print(main())"
    )


def quiesce(client: TDClient) -> None:
    """Stop playback and bypass the heavy Script TOP.

    TD blocks its web server thread while the Script TOP cooks, and the script
    runs CookLevel.ALWAYS -- so it keeps working even with the timeline stopped.
    Saving without doing this reliably stalls TD for one to three minutes.
    """
    client.run(
        "def main():\n"
        "    me.time.play = 0\n"
        f"    sc = op({SCRIPT_TOP!r})\n"
        "    if sc is not None:\n"
        "        sc.bypass = True\n"
        "    return 'quiesced'\n"
        "print(main())"
    )


def resume(client: TDClient) -> None:
    client.run(
        "def main():\n"
        f"    sc = op({SCRIPT_TOP!r})\n"
        "    if sc is not None:\n"
        "        sc.bypass = False\n"
        "    return 'resumed'\n"
        "print(main())"
    )


def save_project(client: TDClient, timeout: float = 420.0) -> str:
    """Save, tolerating the stall. TD often stops answering mid-save for minutes
    and then completes normally, so a timeout here is not a failure."""
    quiesce(client)
    try:
        client.run(
            "import os\n"
            "project.save(os.path.join(project.folder, project.name))\n"
            "print(project.name)",
            timeout=timeout,
        )
        return "saved"
    except Exception:
        if client.wait_until_ready(seconds=timeout):
            return "saved (TD stalled during write, then recovered)"
        raise


def push_all(client: TDClient, cfg: Config, table: CueTable | None = None) -> list[str]:
    done: list[str] = []
    push_params(client, cfg); done.append("params")
    push_field(client); done.append("field script")
    if table is not None:
        push_cues(client, table); done.append(f"{len(table.cues)} cues")
    reset_field_state(client); done.append("state reset")
    return done
